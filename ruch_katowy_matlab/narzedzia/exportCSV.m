function exportCSV(R, plik, format, opis)
%EXPORTCSV Eksport przebiegów do CSV (kolumny jak w aplikacji HTML).
%   exportCSV(R, plik)            – separator „,”, kropka dziesiętna (MATLAB)
%   exportCSV(R, plik, 'excel')   – separator „;”, przecinek dziesiętny (Excel PL, z BOM UTF-8)
%   opis – opcjonalny tekst do wiersza komentarza (np. nazwa projektu)
if nargin < 3 || isempty(format), format = 'matlab'; end
if nargin < 4, opis = ''; end
DEG = pi / 180; ch = R.ch; po = R.post;
C = {'t [s]', ch.t; 'X1 [m]', ch.X1; 'X2 [m]', ch.X2; 'X3 [m]', ch.X3; 'U1 [m/s]', ch.U1; 'U2 [m/s]', ch.U2; 'U3 [m/s]', ch.U3; ...
  'V [m/s]', ch.V; 'Mach [-]', ch.M; 'rho [kg/m3]', ch.rho; 'T_air [K]', ch.Tair; 'p [rad/s]', ch.p; 'q [rad/s]', ch.q; 'r [rad/s]', ch.r; ...
  'psi [deg]', ch.psi / DEG; 'theta [deg]', ch.theta / DEG; 'phi [deg]', ch.phi / DEG; 'alpha [deg]', ch.alpha / DEG; ...
  'alpha_y [deg]', ch.alphaY / DEG; 'beta [deg]', ch.beta / DEG; 'alpha_tot [deg]', ch.alphaTot / DEG; 'phi_A [deg]', ch.phiA / DEG; ...
  'W1 [m/s]', ch.W1; 'W2 [m/s]', ch.W2; 'W3 [m/s]', ch.W3; 'gust_f [-]', ch.gustF; ...
  'K_F_6DOF [deg]', po.KFm / DEG; 'K_S_6DOF [deg]', po.KSm / DEG; 'S_g [-]', po.Sg; 'S_d_0 [-]', po.Sd0; 'S_d_F_A [-]', po.SdFA; ...
  'S_d_S_A [-]', po.SdSA; 'Cmagm_0 [-]', po.Cmagm0; 'Cmagm_F_A [-]', po.CmagmF; 'Cmagm_S_A [-]', po.CmagmS; 'df_ok [-]', po.dfOK; ...
  'nu_F_0 [Hz]', po.nuF0; 'nu_S_0 [Hz]', po.nuS0; 'sigma_F_0 [1/s]', po.sigF0; 'sigma_S_0 [1/s]', po.sigS0; ...
  'sF_re_A [1/s]', po.sFreA; 'sF_im_A [rad/s]', po.sFimA; 'sS_re_A [1/s]', po.sSreA; 'sS_im_A [rad/s]', po.sSimA; ...
  'xi_re [deg]', po.xiRe / DEG; 'xi_im [deg]', po.xiIm / DEG; 'xi_e_re [deg]', po.xieRe / DEG; 'xi_e_im [deg]', po.xieIm / DEG; ...
  'alpha_e_STANAG [deg]', po.aeAbs / DEG; 'alpha_e_STANAG_re [deg]', po.aeRe / DEG; 'alpha_e_STANAG_im [deg]', po.aeIm / DEG; ...
  'K_F [deg]', po.KFabs / DEG; 'K_S [deg]', po.KSabs / DEG; 'env_plus [deg]', po.envP / DEG; 'env_minus [deg]', po.envM / DEG; ...
  'xi_lin_re [deg]', po.xiLinRe / DEG; 'xi_lin_im [deg]', po.xiLinIm / DEG; 'event [-]', ch.ev; 'status [bits]', po.status};
pl = strcmpi(format, 'excel');
if pl, sep = ';'; else, sep = ','; end
X = [C{:, 2}];
fid = fopen(plik, 'w', 'n', 'UTF-8');
if fid < 0, error('Nie mogę otworzyć pliku %s.', plik); end
cl = onCleanup(@() fclose(fid));
if pl, fwrite(fid, [239 187 191], 'uint8'); end
fprintf(fid, '# %s; normowanie %s; u0 = %g m/s; QE = %g %s; wygenerowano %s\n', opis, R.cfg.norm, R.cfg.fire.u0, R.cfg.fire.QE, ...
  R.cfg.fire.QEunit, datestr(now, 'yyyy-mm-ddTHH:MM:SS'));
fprintf(fid, '%s\n', strjoin(C(:, 1).', sep));
for i = 1:size(X, 1)
  s = cell(1, size(X, 2));
  for k = 1:size(X, 2)
    v = X(i, k);
    if ~isfinite(v), s{k} = 'NaN'; elseif v == round(v), s{k} = sprintf('%d', v); else, s{k} = sprintf('%.10g', v); end
  end
  line = strjoin(s, sep);
  if pl, line = strrep(line, '.', ','); end
  fprintf(fid, '%s\n', line);
end
end
