    rows = {'σ_S(α → 0) średnio w locie', sprintf('%s 1/s', fmtPL(uMean(R, po.sigS0, 0, T), 3));
      '|K_S| z 6DOF w 10–30 s', sprintf('średnio %s°, maks. %s°', fmtPL(uMean(R, po.KSm / DEG, 10, 30), 2), fmtPL(mx, 2));
      'C_mag-m: α → 0 | ramię S (10–30 s)', sprintf('%s | %s', fmtPL(uMean(R, po.Cmagm0, 10, 30), 3), fmtPL(uMean(R, po.CmagmS, 10, 30), 3));
      'σ_S przy bieżącej amplitudzie (10–30 s)', sprintf('średnio %s 1/s', fmtPL(uMean(R, po.sSreA, 10, 30), 3));
      'maks. α_tot', sprintf('%s° przy %s s', fmtPL(R.summary.maxAlpha.v, 2), fmtPL(R.summary.maxAlpha.t, 2))};
  end
  function rows = resC2(R)
    M = R.summary.muzzle; po = R.post; r = sqrt(1 - 1 / M.Sg); T = R.ch.t(end);
    t1 = min(8, T); g = uSlope(R, po.KFm, 1, t1);
    if strcmp(R.summary.stop, 'alpha'), kc = 'α_tot = 15°'; else, kc = R.summary.stop; end
    rows = {'S_d u wylotu | prawa gałąź 1 + r', sprintf('%s | %s', fmtPL(M.Sd0, 3), fmtPL(1 + r, 3));
      'σ_F, σ_S u wylotu', sprintf('%s; %s 1/s', fmtPL(M.sigF, 3), fmtPL(M.sigS, 3));
      sprintf('|K_F| z 6DOF przy 1 s i %s s', fmtPL(t1, 0)), sprintf('%s° → %s°', fmtPL(po.KFm(uIdx(R, 1)) / DEG, 3), fmtPL(po.KFm(uIdx(R, t1)) / DEG, 3));
      sprintf('tempo wzrostu |K_F| w 1–%s s: 6DOF | ramię liniowe | średnie σ_F (sekcja 4)', fmtPL(t1, 0)), ...
        sprintf('%s | %s | %s 1/s', fmtPL(g, 3), fmtPL(uSlope(R, po.KFabs, 1, t1), 3), fmtPL(uMean(R, po.sFreA, 1, t1), 3));
      'koniec obliczenia', sprintf('%s po %s s', kc, fmtPL(R.summary.tEnd, 2))};
