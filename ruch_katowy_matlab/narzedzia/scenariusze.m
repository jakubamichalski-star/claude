  function rows = resA(R)
    M = R.summary.muzzle; po = R.post; t = R.ch.t;
    kF = uSlope(R, po.KFm, 0.3, 2.3); kS = uSlope(R, po.KSm, 0.3, 2.3);
    i0 = uIdx(R, 0.3); i10 = find(t > 0.3 & po.KFm < po.KFm(i0) / 10, 1);
    if isempty(i10), z10 = '–'; else, z10 = sprintf('po %s s (ln 10/|σ_F| u wylotu: %s s)', fmtPL(t(i10) - 0.3, 2), fmtPL(log(10) / abs(M.sigF), 2)); end
    rows = {'S_g, S_d u wylotu', sprintf('%s; %s', fmtPL(M.Sg, 2), fmtPL(M.Sd0, 3));
      'ν_F, ν_S u wylotu', sprintf('%s Hz; %s Hz', fmtPL(M.nuF, 2), fmtPL(M.nuS, 2));
      'σ_F, σ_S u wylotu (sekcja 4)', sprintf('%s; %s 1/s', fmtPL(M.sigF, 3), fmtPL(M.sigS, 3));
      'tempo zaniku |K_F|, |K_S| w 0,3–2,3 s: 6DOF | ramiona liniowe', sprintf('%s; %s | %s; %s 1/s', fmtPL(kF, 3), fmtPL(kS, 3), ...
        fmtPL(uSlope(R, po.KFabs, 0.3, 2.3), 3), fmtPL(uSlope(R, po.KSabs, 0.3, 2.3), 3));
      '10-krotny zanik |K_F| od 0,3 s', z10};
  end
  function rows = resB(R)
    M = R.summary.muzzle; po = R.post; i = uIdx(R, min(0.02, R.ch.t(end)));
    re = max(po.sFreA(i), po.sSreA(i));
    if M.Sg < 1, pon = ' – poniżej 1'; else, pon = ''; end
    rows = {'S_g u wylotu', [fmtPL(M.Sg, 3) pon]; 't_c, przy którym S_g = 1', sprintf('%s kal.', fmtPL(R.cfg.fire.tc * sqrt(M.Sg), 1))};
    if M.Sg < 1
      if strcmp(R.summary.stop, 'alpha'), pre = 'α_tot = 15° po '; else, pre = ''; end
      rows = [rows; {'dodatnia część rzeczywista pierwiastka', sprintf('%s 1/s (e-krotny wzrost co %s ms)', fmtPL(re, 1), fmtPL(1000 / re, 0));
        'koniec obliczenia', sprintf('%s%s s', pre, fmtPL(R.summary.tEnd, 3))}];
    else
      rows = [rows; {'σ_F, σ_S u wylotu', sprintf('%s; %s 1/s', fmtPL(M.sigF, 3), fmtPL(M.sigS, 3)); 'ν_F, ν_S u wylotu', sprintf('%s; %s Hz', fmtPL(M.nuF, 2), fmtPL(M.nuS, 2))}];
    end
  end
  function rows = resC1(R)
