  function rows = resD(R)
    ch = R.ch; po = R.post; k = (2:R.n).';
    iM = k(find(ch.M(k - 1) > 1 & ch.M(k) <= 1, 1));
    iS = k(find(po.sSre0(k - 1) <= 0 & po.sSre0(k) > 0, 1)); iD = k(find(po.Sd0(k - 1) > 0 & po.Sd0(k) <= 0, 1));
    if isempty(iM), sM = 'nie występuje'; else, sM = sprintf('po %s s', fmtPL(ch.t(iM), 2)); end
    if isempty(iS), sS = '–'; else, sS = sprintf('%s s (ℳ = %s, S_d = %s)', fmtPL(ch.t(iS), 2), fmtPL(ch.M(iS), 3), fmtPL(po.Sd0(iS), 3)); end
    if isempty(iD), sD = '–'; else, sD = sprintf('%s s (ℳ = %s)', fmtPL(ch.t(iD), 2), fmtPL(ch.M(iD), 3)); end
    rows = {'ℳ₀', fmtPL(ch.M(1), 3); 'ℳ = 1', sM; 'σ_S(α → 0) > 0 od', sS; 'S_d(0) < 0 od', sD;
      'maks. α_tot', sprintf('%s° przy %s s', fmtPL(R.summary.maxAlpha.v, 2), fmtPL(R.summary.maxAlpha.t, 1))};
  end
  function rows = resE(R)
    S = R.summary; po = R.post; Ap = S.apex;
    if ~isempty(Ap), i = uIdx(R, Ap.t); wz = sprintf('%s s, h = %s m, ℳ = %s, S_g = %s', fmtPL(Ap.t, 1), fmtPL(Ap.h, 0), fmtPL(R.ch.M(i), 3), fmtPL(po.Sg(i), 0));
    else, wz = '–'; end
    w = '';
    for q = 1:numel(S.messages)
      if ~isempty(regexp(S.messages(q).text, '^Słaba nadążność', 'once'))
        w = regexprep(regexprep(S.messages(q).text, '^Słaba nadążność: \|ᾱ_e\| > \d+° dla ', ''), ' \(oś nie.*$', ''); break;
      end
    end
    if isempty(w), w = 'nie występuje'; end
    ra = S.runsA(~cellfun(@isempty, regexp({S.runsA.key}, 'dynF', 'once')));
    if isempty(ra), dynF = 'nie'; else, dynF = strjoin(arrayfun(@(r) sprintf('%s–%s s', fmtPL(r.t0, 1), fmtPL(r.t1, 1)), ra, 'UniformOutput', false), ', '); end
    rows = {'wierzchołek', wz; 'maks. |ᾱ_e|', sprintf('%s° przy %s s', fmtPL(S.maxAe.v, 2), fmtPL(S.maxAe.t, 1));
      'maks. α_tot', sprintf('%s° przy %s s', fmtPL(S.maxAlpha.v, 2), fmtPL(S.maxAlpha.t, 1)); '|ᾱ_e| > 5°', w;
      'składowa szybka niestateczna przy bieżącej amplitudzie', dynF};
    g = uGust(R);
    if ~isempty(g)
      [m6, ~] = uMax(R, po.KFm / DEG, g.t + 1, g.t + 35); [ml, ~] = uMax(R, po.KFabs / DEG, g.t + 1, g.t + 35);
      rows = [rows; {'|K_F| po podmuchu: tempo w 1–8 s (6DOF | ramię liniowe)', sprintf('%s | %s 1/s', fmtPL(uSlope(R, po.KFm, g.t + 1, g.t + 8), 4), fmtPL(uSlope(R, po.KFabs, g.t + 1, g.t + 8), 4));
        'maks. |K_F| po podmuchu (6DOF | liniowe)', sprintf('%s° | %s°', fmtPL(m6, 4), fmtPL(ml, 4))}];
    end
  end
  function rows = resF1(R)
    g = uGust(R); if isempty(g), rows = {'podmuch', 'nie wystąpił'}; return; end
    ch = R.ch; po = R.post;
    i0 = find(abs(ch.t - g.t) < 1e-9, 1); i1 = i0; while i1 < R.n && abs(ch.t(i1 + 1) - g.t) < 1e-9, i1 = i1 + 1; end
    dxi = hypot(po.xiRe(i1) - po.xiRe(i0), po.xiIm(i1) - po.xiIm(i0)) / DEG; V = ch.V(i0);
    j = uIdx(R, g.t + 0.3); scenMemo('f1KF', po.KFm(j));
    ratio = hypot(po.sSreA(i1), po.sSimA(i1)) / hypot(po.sFreA(i1), po.sFimA(i1));
    rows = {'podmuch', sprintf('t = %s s, V = %s m/s', fmtPL(g.t, 3), fmtPL(V, 1));
      'skok |ξ|', sprintf('%s° (atan(ΔW/V) = %s°)', fmtPL(dxi, 3), fmtPL(atan(10 / V) / DEG, 3));
      '|K_F|, |K_S| 0,3 s później (6DOF)', sprintf('%s°; %s°', fmtPL(po.KFm(j) / DEG, 4), fmtPL(po.KSm(j) / DEG, 3));
      '|s_S|/|s_F| w chwili podmuchu', fmtPL(ratio, 3)};
  end
  function rows = resF2(R)
    g = uGust(R); e = uGustEnd(R); if isempty(g), rows = {'podmuch', 'nie wystąpił'}; return; end
    po = R.post; j = uIdx(R, e.t + 0.3); i = uIdx(R, g.t);
    pred = gustExcitation('cos', 0.08, complex(po.sFreA(i), po.sFimA(i)));
    rows = {'τ_r·ν_F', fmtPL(0.08 * po.nuF0(i), 2); '|K_F| 0,3 s po narastaniu (6DOF)', sprintf('%s°', fmtPL(po.KFm(j) / DEG, 5));
      'pobudzenie względem skoku wg teorii liniowej', fmtPL(pred, 4)};
    f1 = scenMemo('f1KF');
    if isfinite(f1), rows = [rows; {'stosunek do wariantu skokowego (6DOF)', fmtPL(po.KFm(j) / f1, 4)}]; end
  end
end

