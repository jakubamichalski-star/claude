function x = sc(id, title, goal, set, over, view, look, ask, variants, res)
x = struct('id', id, 'title', title, 'goal', goal, 'set', set, 'over', over, 'view', view, 'look', {look}, 'ask', {ask}, ...
  'variants', {variants}, 'res', res);
end
function s = st(varargin)
s = struct();
for k = 1:2:numel(varargin), s.(varargin{k}) = varargin{k + 1}; end
end
function i = uIdx(R, t)
i = find(R.ch.t <= t, 1, 'last'); if isempty(i), i = 1; end
end
function [v, t] = uMax(R, a, t0, t1)
sel = find(R.ch.t >= t0 & R.ch.t <= t1 & isfinite(a));
if isempty(sel), v = NaN; t = NaN; return; end
[v, j] = max(a(sel)); t = R.ch.t(sel(j));
end
function m = uMean(R, a, t0, t1)
sel = R.ch.t >= t0 & R.ch.t <= t1 & isfinite(a); m = mean(a(sel));
if ~any(sel), m = NaN; end
end
function k = uSlope(R, a, t0, t1)   % d ln(a)/dt – regresja liniowa
sel = R.ch.t >= t0 & R.ch.t <= t1 & a > 0; m = sum(sel);
if m <= 2, k = NaN; return; end
x = R.ch.t(sel); y = log(a(sel));
k = (m * sum(x .* y) - sum(x) * sum(y)) / (m * sum(x .^ 2) - sum(x)^2);
end
function g = uGust(R)
g = [];
for e = R.meta.events
  if strcmp(e.type, 'gust') && ~isempty(regexp(e.text, '^początek podmuchu', 'once')), g = e; return; end
end
end
function g = uGustEnd(R)
e = R.meta.events(strcmp({R.meta.events.type}, 'gust'));
if isempty(e), g = []; else, g = e(end); end
end
